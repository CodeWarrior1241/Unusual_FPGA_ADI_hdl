// Microchip PolarFire port of the Xilinx ad_data_clk: device clock input,
// pad buffer -> global clock network (IBUFGDS + BUFG equivalent, here
// INBUF_DIFF -> CLKINT; Synplify's PolarFire library has no CLKBUF_DIFF).
//
// USE_PLL_90 = 1 additionally runs the buffered clock through a PF_CCC
// (component PF_CCC_C1, generated by the project build script):
//   clk    = OUT0, 0 degrees
//   clk_90 = OUT1, +90 degrees
// The CCC runs Post-VCO feedback, which guarantees the OUT0/OUT1 phase
// relationship (outputs are resynchronized to each other after lock, NOT
// to the reference). clk_90 exists for the TX FB_CLK output structure:
// all TX pads launch from identical fabric DDR muxes, so a matched clock
// puts the forwarded-clock edges exactly on the data transitions and the
// AD9361 samples at the eye edge; launching only FB_CLK from +90 centers
// its edges in the data eye (quarter of the 16.276 ns DATA_CLK period =
// 4.07 ns) across corners, which per-bit routing detours cannot achieve.
// With USE_PLL_90 = 0 the original INBUF_DIFF -> CLKINT path is used and
// clk_90 is just clk.

`timescale 1ns/100ps

module ad_data_clk #(

  parameter   SINGLE_ENDED = 0,
  parameter   USE_PLL_90 = 0
) (

  input               rst,
  output              locked,

  input               clk_in_p,
  input               clk_in_n,
  output              clk,
  output              clk_90
);

  wire clk_ibuf_s;

  generate
  if (SINGLE_ENDED == 1) begin
    assign locked = 1'b1;
    CLKBUF i_rx_clk_gbuf (
      .PAD (clk_in_p),
      .Y (clk));
    assign clk_90 = clk;
  end else if (USE_PLL_90 == 0) begin
    assign locked = 1'b1;
    INBUF_DIFF i_rx_clk_ibuf (
      .PADP (clk_in_p),
      .PADN (clk_in_n),
      .Y (clk_ibuf_s));
    CLKINT i_rx_clk_gbuf (
      .A (clk_ibuf_s),
      .Y (clk));
    assign clk_90 = clk;
  end else begin
    wire clk_ref_s;
    INBUF_DIFF i_rx_clk_ibuf (
      .PADP (clk_in_p),
      .PADN (clk_in_n),
      .Y (clk_ibuf_s));
    // CLKINT_PRESERVE routes the reference to the CCC through the fabric
    // global network: the DATA_CLK pin is dictated by the FMC pinout and
    // is not a CCC-function pin, so the dedicated PLL connection is
    // unavailable (P&R errors with PDCPF-13 otherwise). PRESERVE, not
    // plain CLKINT, or Synplify optimizes the buffer away and reinstates
    // the dedicated-routing rule (same idiom as the project refclk).
    CLKINT_PRESERVE i_rx_clk_gbuf (
      .A (clk_ibuf_s),
      .Y (clk_ref_s));
    PF_CCC_C1 i_ccc (
      .PLL_POWERDOWN_N_0 (1'b1),
      .REF_CLK_0 (clk_ref_s),
      .OUT0_FABCLK_0 (clk),
      .OUT1_FABCLK_0 (clk_90),
      .PLL_LOCK_0 (locked));
  end
  endgenerate

endmodule
